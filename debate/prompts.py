from __future__ import annotations


def render(template: str, **values) -> str:
    """安全填充模板：只替换 {name} 占位符，保留模板中的 JSON 花括号。"""
    for key, value in values.items():
        template = template.replace("{" + key + "}", str(value))
    return template


