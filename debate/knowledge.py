# 五、安全表达清单（避免编造数据）
SAFE_EXPRESSION = [
    "不使用具体数字、百分比、年份、机构名、研究结论或具体事件名，除非输入中确实给出",
    "确需表达趋势时用可核验的泛指（如“有研究表明”这类模糊背书也应尽量避免，改为讲道理）",
    "优先用逻辑推理、类比、反例与衡量标准来论证，而非依赖数据",
]


def knowledge_block() -> str:
    """生成注入提示词的知识块；DEBATE_KB=off 时返回空串。"""
    if not kb_enabled():
        return ""
    lines: list[str] = ["【辩论知识库（供参考，勿照抄、勿编造数据）】"]
    lines.append("一、常见逻辑谬误与驳法：")
    for f in FALLACIES:
        lines.append(f"- {f['name']}：{f['sign']}；可追问：{f['probe']}；驳法：{f['rebut']}")
    lines.append("二、论证评估三标准：" + "；".join(CRITERIA))
    lines.append("三、驳论四步法：" + "；".join(REBUT_STEPS))
    lines.append("三点五、标准反驳路径（优先级由高到低）：" + "；".join(REBUT_PATHS))
    lines.append("四、图尔敏论证六要素（反驳首选攻击“保证”这一隐含前提）：" + "；".join(TOULMIN))
    lines.append("五、立论四要素：" + "；".join(CASE_ELEMENTS))
    lines.append("六、总结陈词结构：" + "；".join(WHIP_STRUCTURE))
    lines.append("七、质询应对：" + "；".join(POI_REPLY))
    lines.append("八、常见辩题双方论点（择要参考，勿机械罗列）：")
    for topic, sides in TOPIC_HINTS.items():
        lines.append(f"- {topic}｜支持方：{' / '.join(sides['pro'])}｜反对方：{' / '.join(sides['con'])}")
    lines.append("九、安全表达：" + "；".join(SAFE_EXPRESSION))
    return "\n".join(lines)
